export function renderInfo(root, ctx) {
  const key = ctx.segments[0] || 'about';
  const page = PAGES[key] || PAGES.about;
  root.innerHTML = `<div class="view-enter">
    <div class="page-hero">
      <div class="section-kicker">${page.kicker}</div>
      <h1>${page.title}</h1>
      <p>${page.lead}</p>
    </div>
    <div class="stack" style="gap:18px;margin-bottom:60px">
      ${page.sections.map(([title, text]) => `<div class="panel panel-pad">
        <div class="row" style="gap:10px;margin-bottom:8px">
          <span class="cat-icon" style="width:34px;height:34px">${icon('bookOpen')}</span>
          <h3 style="font-size:18px">${title}</h3>
        </div>
        <p class="prose">${text}</p>
      </div>`).join('')}
    </div>
  </div>`;
}
